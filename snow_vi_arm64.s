DATA snowViARMConstants<>+8(SB)/8, $0x4a6d4a6d4a6d4a6d
DATA snowViARMConstants<>+16(SB)/8, $0xcc87cc87cc87cc87
DATA snowViARMConstants<>+24(SB)/8, $0xcc87cc87cc87cc87
DATA snowViARMConstants<>+32(SB)/8, $0x0d0905010c080400
DATA snowViARMConstants<>+40(SB)/8, $0x0f0b07030e0a0602
DATA snowViARMConstants<>+48(SB)/8, $0x8000800080008000
DATA snowViARMConstants<>+56(SB)/8, $0x8000800080008000
GLOBL snowViARMConstants<>(SB), (NOPTR+RODATA), $64

// Complemented reductions let BCAX compute shift xor (mask and polynomial).
DATA snowViARMSHA3Constants<>+0(SB)/8, $0xb592b592b592b592
DATA snowViARMSHA3Constants<>+8(SB)/8, $0xb592b592b592b592
DATA snowViARMSHA3Constants<>+16(SB)/8, $0x3378337833783378
DATA snowViARMSHA3Constants<>+24(SB)/8, $0x3378337833783378
GLOBL snowViARMSHA3Constants<>(SB), (NOPTR+RODATA), $32

// V0=A0, V1=B0, V2=A1, V3=B1, V4-V6=R1-R3, V7=output.
// V8-V23 hold secret FSM, LFSR, AES, and caller-input temporaries.
// V24/V25 are public reduction constants, V28 is sigma, V30 is the
// high-bit mask, and V31 is zero. General registers hold public pointers/counts.
#define SNOWVI_ARM64_LFSR \
	VEXT $14, V2.B16, V0.B16, V10.B16; \
	VSHL $1, V0.H8, V12.H8; \
	VSHL $1, V1.H8, V13.H8; \
	VCMTST V30.H8, V0.H8, V16.H8; \
	VCMTST V30.H8, V1.H8, V17.H8; \
	VAND V24.B16, V16.B16, V16.B16; \
	VAND V25.B16, V17.B16, V17.B16; \
	VEOR V16.B16, V12.B16, V12.B16; \
	VEOR V17.B16, V13.B16, V13.B16; \
	VEOR V1.B16, V12.B16, V12.B16; \
	VEOR V10.B16, V12.B16, V12.B16; \
	VEOR V0.B16, V13.B16, V13.B16; \
	VEOR V3.B16, V13.B16, V13.B16; \
	VMOV V2.B16, V0.B16; \
	VMOV V3.B16, V1.B16; \
	VMOV V12.B16, V2.B16; \
	VMOV V13.B16, V3.B16

#define SNOWVI_ARM64_CORE_STEP \
	VADD V3.S4, V4.S4, V7.S4; \
	VEOR V5.B16, V7.B16, V7.B16; \
	VEOR V2.B16, V6.B16, V8.B16; \
	VADD V8.S4, V5.S4, V8.S4; \
	VTBL V28.B16, [V8.B16], V9.B16; \
	AESE V31.B16, V4.B16; \
	AESMC V4.B16, V4.B16; \
	AESE V31.B16, V5.B16; \
	AESMC V5.B16, V5.B16; \
	SNOWVI_ARM64_LFSR; \
	VMOV V5.B16, V6.B16; \
	VMOV V4.B16, V5.B16; \
	VMOV V9.B16, V4.B16

#define SNOWVI_ARM64_LFSR_SHA3 \
	VEXT $14, V2.B16, V0.B16, V10.B16; \
	VSHL $1, V0.H8, V12.H8; \
	VSHL $1, V1.H8, V13.H8; \
	VCMTST V30.H8, V0.H8, V16.H8; \
	VCMTST V30.H8, V1.H8, V17.H8; \
	VBCAX V24.B16, V16.B16, V12.B16, V12.B16; \
	VBCAX V25.B16, V17.B16, V13.B16, V13.B16; \
	VEOR3 V10.B16, V1.B16, V12.B16, V12.B16; \
	VEOR3 V3.B16, V0.B16, V13.B16, V13.B16; \
	VMOV V2.B16, V0.B16; \
	VMOV V3.B16, V1.B16; \
	VMOV V12.B16, V2.B16; \
	VMOV V13.B16, V3.B16

#define SNOWVI_ARM64_CORE_STEP_SHA3(SRC) \
	VADD V3.S4, V4.S4, V7.S4; \
	VEOR3 V5.B16, V7.B16, SRC.B16, SRC.B16; \
	VEOR V2.B16, V6.B16, V8.B16; \
	VADD V8.S4, V5.S4, V8.S4; \
	AESE V31.B16, V4.B16; \
	AESMC V4.B16, V4.B16; \
	AESE V31.B16, V5.B16; \
	AESMC V5.B16, V5.B16; \
	VTBL V28.B16, [V8.B16], V9.B16; \
	SNOWVI_ARM64_LFSR_SHA3; \
	VMOV V5.B16, V6.B16; \
	VMOV V4.B16, V5.B16; \
	VMOV V9.B16, V4.B16

#define LOAD_SNOWVI_ARM64_CONSTANTS \
	MOVD $snowViARMConstants<>(SB), R4; \
	VLD1.P 32(R4), [V24.B16, V25.B16]; \
	VLD1.P 16(R4), [V28.B16]; \
	VLD1 (R4), [V30.B16]; \
	VEOR V31.B16, V31.B16, V31.B16

#define LOAD_SNOWVI_ARM64_SHA3_CONSTANTS \
	MOVD $snowViARMSHA3Constants<>(SB), R4; \
	VLD1 (R4), [V24.B16, V25.B16]; \
	MOVD $snowViARMConstants<>+32(SB), R4; \
	VLD1.P 16(R4), [V28.B16]; \
	VLD1 (R4), [V30.B16]; \
	VEOR V31.B16, V31.B16, V31.B16

#define LOAD_SNOWVI_ARM64_STATE \
	VLD1 (R0), [V0.B16, V1.B16, V2.B16, V3.B16]; \
	ADD $snowVState_r1, R0, R5; \
	VLD1 (R5), [V4.B16, V5.B16, V6.B16]

#define STORE_SNOWVI_ARM64_STATE \
	VST1 [V0.B16, V1.B16, V2.B16, V3.B16], (R0); \
	ADD $snowVState_r1, R0, R5; \
	VST1 [V4.B16, V5.B16, V6.B16], (R5)

#define WIPE_SNOWVI_ARM64_VECTORS \
	VEOR V0.B16, V0.B16, V0.B16; \
	VEOR V1.B16, V1.B16, V1.B16; \
	VEOR V2.B16, V2.B16, V2.B16; \
	VEOR V3.B16, V3.B16, V3.B16; \
	VEOR V4.B16, V4.B16, V4.B16; \
	VEOR V5.B16, V5.B16, V5.B16; \
	VEOR V6.B16, V6.B16, V6.B16; \
	VEOR V7.B16, V7.B16, V7.B16; \
	VEOR V8.B16, V8.B16, V8.B16; \
	VEOR V9.B16, V9.B16, V9.B16; \
