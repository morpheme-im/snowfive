// func initStateViARM64(state *snowVState, key, iv *byte)
// The secret register map is complete above; every vector register is wiped.
TEXT ·initStateViARM64(SB), NOSPLIT, $0
	MOVD state+0(FP), R0
	MOVD key+8(FP), R1
	MOVD iv+16(FP), R2
	LOAD_SNOWVI_ARM64_CONSTANTS
	VLD1 (R2), [V0.B16]
	VEOR V1.B16, V1.B16, V1.B16
	VLD1 (R1), [V2.B16, V3.B16]
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	MOVD $14, R3
initViARM64Loop14:
	SNOWVI_ARM64_CORE_STEP
	VEOR V7.B16, V2.B16, V2.B16
	SUBS $1, R3
	BNE initViARM64Loop14
	SNOWVI_ARM64_CORE_STEP
	VEOR V7.B16, V2.B16, V2.B16
	VLD1 (R1), [V23.B16]
	VEOR V23.B16, V4.B16, V4.B16
	SNOWVI_ARM64_CORE_STEP
	VEOR V7.B16, V2.B16, V2.B16
	ADD $16, R1, R5
	VLD1 (R5), [V23.B16]
	VEOR V23.B16, V4.B16, V4.B16
	STORE_SNOWVI_ARM64_STATE
	WIPE_SNOWVI_ARM64_VECTORS
	RET

// func xorBlocksViARM64(state *snowVState, dst, src *byte, blocks uintptr)
// Input is fully loaded before output stores; branches depend only on blocks.
TEXT ·xorBlocksViARM64(SB), NOSPLIT, $0
	MOVD state+0(FP), R0
	MOVD dst+8(FP), R1
	MOVD src+16(FP), R2
	MOVD blocks+24(FP), R3
	LOAD_SNOWVI_ARM64_CONSTANTS
	LOAD_SNOWVI_ARM64_STATE
	CMP $4, R3
	BLT streamViARM64Remainder
streamViARM64Loop4:
	VLD1.P 64(R2), [V20.B16, V21.B16, V22.B16, V23.B16]
	SNOWVI_ARM64_CORE_STEP
	VEOR V20.B16, V7.B16, V20.B16
	SNOWVI_ARM64_CORE_STEP
	VEOR V21.B16, V7.B16, V21.B16
	SNOWVI_ARM64_CORE_STEP
	VEOR V22.B16, V7.B16, V22.B16
	SNOWVI_ARM64_CORE_STEP
	VEOR V23.B16, V7.B16, V23.B16
	VST1.P [V20.B16, V21.B16, V22.B16, V23.B16], 64(R1)
	SUB $4, R3
	CMP $4, R3
	BGE streamViARM64Loop4
streamViARM64Remainder:
	CBZ R3, streamViARM64Done
streamViARM64RemainderLoop:
	VLD1.P 16(R2), [V23.B16]
	SNOWVI_ARM64_CORE_STEP
	VEOR V23.B16, V7.B16, V7.B16
	VST1.P [V7.B16], 16(R1)
	SUBS $1, R3
	BNE streamViARM64RemainderLoop
streamViARM64Done:
	STORE_SNOWVI_ARM64_STATE
	WIPE_SNOWVI_ARM64_VECTORS
	RET

// func xorBlocksViARM64SHA3(state *snowVState, dst, src *byte, blocks uintptr)
// FEAT_SHA3 is required. EOR3/BCAX specialize the streaming LFSR only.
TEXT ·xorBlocksViARM64SHA3(SB), NOSPLIT, $0
	MOVD state+0(FP), R0
	MOVD dst+8(FP), R1
	MOVD src+16(FP), R2
	MOVD blocks+24(FP), R3
	LOAD_SNOWVI_ARM64_SHA3_CONSTANTS
	LOAD_SNOWVI_ARM64_STATE
	CMP $4, R3
	BLT streamViARM64SHA3Remainder
streamViARM64SHA3Loop4:
	VLD1.P 64(R2), [V20.B16, V21.B16, V22.B16, V23.B16]
	SNOWVI_ARM64_CORE_STEP_SHA3(V20)
	SNOWVI_ARM64_CORE_STEP_SHA3(V21)
	SNOWVI_ARM64_CORE_STEP_SHA3(V22)
	SNOWVI_ARM64_CORE_STEP_SHA3(V23)
	VST1.P [V20.B16, V21.B16, V22.B16, V23.B16], 64(R1)
	SUB $4, R3
	CMP $4, R3
	BGE streamViARM64SHA3Loop4
streamViARM64SHA3Remainder:
	CBZ R3, streamViARM64SHA3Done
streamViARM64SHA3RemainderLoop:
	VLD1.P 16(R2), [V23.B16]
	SNOWVI_ARM64_CORE_STEP_SHA3(V23)
	VST1.P [V23.B16], 16(R1)
	SUBS $1, R3
	BNE streamViARM64SHA3RemainderLoop
streamViARM64SHA3Done:
	STORE_SNOWVI_ARM64_STATE
	WIPE_SNOWVI_ARM64_VECTORS
	RET
